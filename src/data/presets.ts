export function hasCollision(
  candidate: { id?: string; x: number; y: number; w: number; h: number },
  modules: SynthModule[],
  grid: GridDimensions
): boolean {
  if (
    candidate.x < 0 ||
    candidate.y < 0 ||
    candidate.x + candidate.w > grid.cols ||
    candidate.y + candidate.h > grid.rows
  ) {
    return true;
  }
  return modules.some((m) => {
    if (candidate.id && m.id === candidate.id) return false;
    const overlapX = candidate.x < m.x + m.w && candidate.x + candidate.w > m.x;
    const overlapY = candidate.y < m.y + m.h && candidate.y + candidate.h > m.y;
    return overlapX && overlapY;
  });
}

export function findFirstOpenSlot(
  w: number,
  h: number,
  modules: SynthModule[],
  grid: GridDimensions
): { x: number; y: number } | null {
  for (let row = 0; row <= grid.rows - h; row++) {
    for (let col = 0; col <= grid.cols - w; col++) {
      if (!hasCollision({ x: col, y: row, w, h }, modules, grid)) {
        return { x: col, y: row };
      }
    }
  }
  return null;
}

export const BASE_CELL_W = 86;
export const BASE_CELL_H = 74;
export const BASE_GAP = 8;

export function getModulePixelRect(m: SynthModule): {
  px: number;
  py: number;
  pw: number;
  ph: number;
} {
  return {
    px: m.px ?? m.x * BASE_CELL_W + 18,
    py: m.py ?? m.y * BASE_CELL_H + 18,
    pw: m.pw ?? Math.max(76, m.w * BASE_CELL_W - BASE_GAP),
    ph: m.ph ?? Math.max(62, m.h * BASE_CELL_H - BASE_GAP),
  };
}

export function hydrateModulesWithPixels(modules: SynthModule[]): SynthModule[] {
  return modules.map((m) => {
    const rect = getModulePixelRect(m);
    return { ...m, ...rect };
  });
}

export function findOpenPixelSlot(
  pw: number,
  ph: number,
  modules: SynthModule[],
  canvasW = 1280,
  canvasH = 920
): { px: number; py: number } {
  const stepX = 24;
  const stepY = 24;
  const padX = 18;
  const startY = 18;
  const rects = modules.map(getModulePixelRect);

  for (let y = startY; y <= canvasH - ph - 16; y += stepY) {
    for (let x = padX; x <= canvasW - pw - padX; x += stepX) {
      const overlaps = rects.some(
        (r) => x < r.px + r.pw + 6 && x + pw + 6 > r.px && y < r.py + r.ph + 6 && y + ph + 6 > r.py
      );
      if (!overlaps) {
        return { px: x, py: y };
      }
    }
  }
  const offset = (modules.length % 8) * 20;
  return { px: 40 + offset, py: startY + offset };
}

export function createModuleFromPalette(
  def: PaletteItemDefinition,
  x: number,
  y: number,
  px?: number,
  py?: number,
  tabId?: string
): SynthModule {
  const pw = Math.max(76, def.defaultW * BASE_CELL_W - BASE_GAP);
  const ph = Math.max(62, def.defaultH * BASE_CELL_H - BASE_GAP);
  return {
    id: `mod-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
    tabId,
    type: def.type,
    label: def.name,
    x,
    y,
    w: def.defaultW,
    h: def.defaultH,
    px: px ?? x * BASE_CELL_W + 16,
    py: py ?? y * BASE_CELL_H + 16,
    pw,
    ph,
    accent: def.defaultAccent,
    midi: { ...def.defaultMidi },
    secondaryMidi: def.defaultSecondaryMidi ? { ...def.defaultSecondaryMidi } : undefined,
    config: {
      ...def.defaultConfig,
      options: def.defaultConfig.options
        ? def.defaultConfig.options.map((o) => ({ ...o }))
        : undefined,
    },
    values: {
      ...def.defaultValues,
      adsr: def.defaultValues.adsr ? { ...def.defaultValues.adsr } : undefined,
      adsrEnvelopes:
        def.type === 'adsr' ? structuredClone(DEFAULT_ADSR_ENVELOPES) : undefined,
      seqSteps: def.defaultValues.seqSteps
        ? def.defaultValues.seqSteps.map((s) => ({ ...s }))
        : undefined,
    },
  };
}

